public class Estado {

    int swap;
    int peso;

    public Estado(int swap, int peso) {
        this.swap = swap;
        this.peso = peso;
    }

    public int getSwap() {
        return swap;
    }
    public long getPeso() {
        return peso;
    }

    public void setSwap(int swap) {
        this.swap = swap;
    }
    public void setPeso(int peso) {
        this.peso = peso;
    }

}
